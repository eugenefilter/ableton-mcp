#!/bin/bash

# Скрипт для полной установки и запуска AI Ableton Agent

# --- Шаг 1: Установка зависимостей ---
echo "--- (1/3) Установка зависимостей из requirements.txt... ---"

pip install -r requirements.txt

# Проверка, что установка прошла успешно
if [ $? -ne 0 ]; then
    echo "Ошибка при установке зависимостей. Пожалуйста, проверьте pip и Python."
    exit 1
fi

echo "Зависимости успешно установлены."

# --- Шаг 2: Копирование скрипта в Ableton ---
echo "\n--- (2/3) Копирование Control Surface скрипта в Ableton... ---"

python setup.py

# Проверка, что копирование прошло успешно
if [ $? -ne 0 ]; then
    echo "Ошибка при копировании скрипта. Пожалуйста, проверьте вывод setup.py."
    exit 1
fi

echo "Скрипт успешно скопирован."

# --- Шаг 3: Запуск моста ---
echo "\n--- (3/3) Запуск сервера-моста... ---"
echo "Сервер будет работать в этом окне терминала. Не закрывайте его."
echo "Для остановки сервера нажмите Ctrl+C."

python bridge.py
